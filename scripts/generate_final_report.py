"""
Script to generate docs/final_report.md and update README.md tables directly
from saved result files:
- outputs/gold_audit_results.json
- outputs/search_eval_results.json
- outputs/search_experiments.json
- outputs/qa_log.md
- outputs/bid1.json, outputs/bid2.json, outputs/bid3.json

Follows Working Rule: Every table in the README and final report must be
generated by script directly from saved result files; never type numbers by hand.
"""

import json
import re
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent


def load_json(rel_path: str):
    p = PROJECT_ROOT / rel_path
    if not p.exists():
        raise FileNotFoundError(f"Missing required result file: {p}")
    with open(p, "r", encoding="utf-8") as f:
        return json.load(f)


def build_section_1_gold_table(gold_data):
    lines = []
    lines.append("| Bid Package | Total Fields | Strict Matches | Expected Null OK | Mismatches | Missing (Null) | Strict Accuracy |")
    lines.append("|---|---|---|---|---|---|---|")
    for bid_id in ["Bid1", "Bid2", "Bid3"]:
        b = gold_data["bids"][bid_id]
        lines.append(
            f"| **{bid_id}** | {b['total']} | {b['matches']} | {b['expected_null_ok']} | {b['mismatches']} | {b['missing']} | **{b['accuracy']:.1f}%** ({b['correct']}/{b['total']}) |"
        )
    lines.append(
        f"| **Overall** | **{gold_data['total_fields']}** | **{gold_data['matches']}** | **{gold_data['expected_null_ok']}** | **{gold_data['mismatches']}** | **{gold_data['missing']}** | **{gold_data['overall_accuracy']:.1f}%** ({gold_data['matches'] + gold_data['expected_null_ok']}/{gold_data['total_fields']}) |"
    )
    return "\n".join(lines)


def build_section_3_search_table(search_data):
    metrics = search_data["metrics"]
    mode_names = {
        "bm25_only": "BM25 Only",
        "dense_only": "Dense Only (BGE-small)",
        "hybrid_norerank": "Hybrid (RRF k=60)",
        "hybrid_rerank": "Hybrid + Cross-Encoder Rerank",
    }
    order = ["bm25_only", "dense_only", "hybrid_norerank", "hybrid_rerank"]
    lines = []
    lines.append("| Retrieval Mode | Recall@1 | Recall@3 | Recall@5 | MRR | Latency (avg) |")
    lines.append("|---|---|---|---|---|---|")
    for k in order:
        m = metrics.get(k, {})
        name = mode_names.get(k, k)
        r1 = f"{m.get('recall_at_1', 0.0) * 100:.2f}%"
        r3 = f"{m.get('recall_at_3', 0.0) * 100:.2f}%"
        r5 = f"{m.get('recall_at_5', 0.0) * 100:.2f}%"
        mrr = f"{m.get('mrr', 0.0):.4f}"
        lat = f"{m.get('latency_ms', 0.0):.1f} ms"
        lines.append(f"| **{name}** | {r1} | {r3} | {r5} | {mrr} | {lat} |")
    return "\n".join(lines)


def build_section_4_d3_table(d3_data):
    lines = []
    lines.append("| Experiment | Description | Status | Delta R@1 | Delta R@5 | Delta MRR | Outcome / Decision |")
    lines.append("|---|---|---|---|---|---|---|")
    for exp_key in ["exp_a_table_row_groups", "exp_b_bge_base", "exp_c_weighted_rrf", "exp_d_bm25_query_expansion"]:
        exp = d3_data.get(exp_key, {})
        name = exp.get("name", exp_key)
        status = exp.get("status", "run")
        dr1 = f"{exp.get('delta_r1', 0.0):+.4f}" if status == "run" else "N/A"
        dr5 = f"{exp.get('delta_r5', 0.0):+.4f}" if status == "run" else "N/A"
        dmrr = f"{exp.get('delta_mrr', 0.0):+.4f}" if status == "run" else "N/A"
        decision = "**Kept**" if exp.get("kept") else "Not adopted"
        notes = exp.get("notes", exp.get("reason", ""))
        lines.append(f"| **{name}** | {notes} | `{status}` | {dr1} | {dr5} | {dmrr} | {decision} |")
    return "\n".join(lines)


def build_section_5_qa_table():
    qa_path = PROJECT_ROOT / "outputs" / "qa_log.md"
    content = qa_path.read_text(encoding="utf-8")
    blocks = [b.strip() for b in content.split("## Q") if b.strip() and not b.startswith("# QA Log")]
    lines = []
    lines.append("| Q# | Question | Routed Bid | Citations Count | Key Answer / Verified Fact |")
    lines.append("|---|---|---|---|---|")
    for block in blocks:
        q_match = re.match(r"^(\d+):\s*(.+)", block.split("\n")[0])
        if not q_match:
            continue
        q_num = q_match.group(1)
        q_text = q_match.group(2).strip()
        routed_match = re.search(r"\*\*Routed to:\*\*\s*`([^`]+)`", block)
        routed = routed_match.group(1) if routed_match else "Multi-Bid / Comparison"
        citations = re.findall(r"\d+\.\s*`([^`]+)`\s*\(p\.(\d+)\)", block)
        cite_count = len(citations)
        # Extract first sentence of answer
        ans_match = re.search(r"\*\*Answer:\*\*\s*\n+([^\n]+)", block)
        ans_snippet = ans_match.group(1).strip() if ans_match else "Answer recorded"
        if len(ans_snippet) > 85:
            ans_snippet = ans_snippet[:82] + "..."
        # Escape markdown pipes
        ans_snippet = ans_snippet.replace("|", "&#124;")
        q_text = q_text.replace("|", "&#124;")
        lines.append(f"| **Q{q_num}** | {q_text} | `{routed}` | {cite_count} | {ans_snippet} |")
    return "\n".join(lines)


def build_section_6_confidence_table():
    lines = []
    lines.append("| Bid Package | Non-Null Fields | Min Conf | Max Conf | Mean Conf | Score Distribution `[<=0.3, 0.3-0.6, 0.6-0.8, 0.8-1.0]` | Distinct Score Values |")
    lines.append("|---|---|---|---|---|---|---|")
    for bid_id in ["bid1", "bid2", "bid3"]:
        data = load_json(f"outputs/{bid_id}.json")
        confs = [f["confidence"] for f in data["fields"].values() if f.get("value") is not None and f.get("confidence") is not None]
        b1 = sum(1 for c in confs if c <= 0.3)
        b2 = sum(1 for c in confs if 0.3 < c <= 0.6)
        b3 = sum(1 for c in confs if 0.6 < c <= 0.8)
        b4 = sum(1 for c in confs if 0.8 < c <= 1.0)
        min_c = min(confs) if confs else 0.0
        max_c = max(confs) if confs else 0.0
        mean_c = sum(confs) / len(confs) if confs else 0.0
        distinct = sorted(list(set(confs)))
        dist_str = f"`{[b1, b2, b3, b4]}`"
        distinct_str = ", ".join(str(d) for d in distinct)
        lines.append(
            f"| **{bid_id.upper()}** | {len(confs)} | {min_c:.2f} | {max_c:.2f} | **{mean_c:.2f}** | {dist_str} | `{distinct_str}` |"
        )
    return "\n".join(lines)


